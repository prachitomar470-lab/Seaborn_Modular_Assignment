import pandas as pd
import numpy as np

np.random.seed(42)

data = {
    'delivery_time': np.random.randint(15, 60, 20),
    'order_value': np.random.randint(100, 1000, 20),
    'tip_amount': np.random.randint(10, 100, 20),
    'rating': np.random.randint(1, 6, 20),
    'delivery_distance': np.random.randint(1, 20, 20)
}

df = pd.DataFrame(data)

print(df.head())
correlation_matrix = df.corr()

print("\nCorrelation Matrix:")
print(correlation_matrix)

import seaborn as sns
import matplotlib.pyplot as plt

sns.heatmap(
    correlation_matrix,
    annot=True,
    fmt='.2f'
)

plt.title('Food Delivery Correlation Heatmap')
plt.show()

sns.heatmap(
    correlation_matrix,
    annot=True,
    fmt='.2f',
    cmap='coolwarm',
    vmin=-1,
    vmax=1,
    center=0
)

plt.title('Food Delivery Correlation Heatmap')
plt.show()

