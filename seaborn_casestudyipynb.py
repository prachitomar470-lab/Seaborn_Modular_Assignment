import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

bank_df = pd.read_csv('/content/bank-additional-full.csv', sep=';')
print(bank_df.head(10))
bank_df.info()

sns.countplot(data=bank_df, x='y')

plt.title('Term Deposit Subscription Count')
plt.xlabel('Subscribed to Term Deposit')
plt.ylabel('Number of Customers')
plt.show()

sns.boxplot(data=bank_df, x='y', y='age')

plt.title('Customer Age vs Term Deposit Subscription')
plt.xlabel('Term Deposit Subscription')
plt.ylabel('Customer Age')
plt.show()

education_percentage = (
    bank_df.groupby('education')['y']
    .apply(lambda x: (x == 'yes').mean() * 100)
    .reset_index(name='Subscription_Percentage')
)

print(education_percentage)

sns.barplot(
    data=education_percentage,
    x='education',
    y='Subscription_Percentage'
)

plt.title('Subscription Percentage by Education Level')
plt.xlabel('Education Level')
plt.ylabel('Subscription Percentage (%)')
plt.xticks(rotation=45)

plt.tight_layout()
plt.show()

campaign_percentage = (
    bank_df.groupby('poutcome')['y']
    .apply(lambda x: (x == 'yes').mean() * 100)
    .reset_index(name='Subscription_Percentage')
)

print(campaign_percentage)
sns.barplot(
    data=campaign_percentage,
    x='poutcome',
    y='Subscription_Percentage'
)

plt.title('Subscription Rate by Previous Campaign Outcome')
plt.xlabel('Previous Campaign Outcome')
plt.ylabel('Subscription Percentage (%)')

plt.tight_layout()
plt.show()