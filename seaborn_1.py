import seaborn as sns
import matplotlib.pyplot as plt

days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun']
temps = [32, 34, 33, 35, 36, 37, 34]

# Theme 1: Dark Grid
sns.set_theme(style='darkgrid')

plt.figure(figsize=(8, 4))
sns.lineplot(x=days, y=temps, marker='o')
plt.xlabel("Days")
plt.ylabel("Temperature (°C)")
plt.title("Weekly Temperature Trend - Dark Grid")
plt.savefig("temperature_darkgrid.png", dpi=150)
plt.show()


# Theme 2: White Grid
sns.set_theme(style='whitegrid')

plt.figure(figsize=(8, 4))
sns.lineplot(x=days, y=temps, marker='o')
plt.xlabel("Days")
plt.ylabel("Temperature (°C)")
plt.title("Weekly Temperature Trend - White Grid")
plt.savefig("temperature_whitegrid.png", dpi=150)
plt.show()


# Theme 3: Ticks
sns.set_theme(style='ticks')

plt.figure(figsize=(8, 4))
sns.lineplot(x=days, y=temps, marker='o')
plt.xlabel("Days")
plt.ylabel("Temperature (°C)")
plt.title("Weekly Temperature Trend - Ticks")
plt.savefig("temperature_ticks.png", dpi=150)
plt.show()

