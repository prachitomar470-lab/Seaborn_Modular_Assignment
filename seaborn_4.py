import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

data = {
    'Product': ['Phone', 'Laptop', 'Tablet', 'Watch',
                'Headphones', 'Camera', 'Speaker', 'TV'],
    'Price': [12000, 45000, 18000, 3000,
              2500, 35000, 5000, 60000]
}

df = pd.DataFrame(data)

df.to_csv('flipkart_prices.csv', index=False)

df = pd.read_csv('flipkart_prices.csv')

print(df.head())

sns.boxplot(x=df['Price'])

plt.title('Flipkart Product Price Distribution')
plt.xlabel('Price (Rs)')
plt.show()

